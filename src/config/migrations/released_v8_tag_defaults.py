def apply_tag_defaults(defaults, schema_version):
    """Project an independent v8.6 default tree to the requested tagged schema."""
    deltas = [(_V81_REMOVED, _V81_REPLACEMENTS)]
    if schema_version == "v8.0.0":
        deltas.append((_V80_REMOVED, _V80_REPLACEMENTS))

    for removed, replacements in deltas:
        for path in removed:
            target, key = _owner(defaults, path)
            del target[key]
        for path, value in replacements.items():
            target, key = _owner(defaults, path)
            target[key] = deepcopy(value)


def _owner(defaults, path):
    *parents, key = path.split(".")
    target = defaults
    for parent in parents:
        target = target[parent]
    return target, key
