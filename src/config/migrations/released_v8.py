def get_released_v8_defaults(*, strategy_kind=None):
    """Return independent copies of the public v8.6 schema and search defaults.

    Passing a strategy kind projects the same active-strategy subtrees that the
    released loader retained. Omitting it returns the complete released schema,
    including removed strategies for inspecting their original policy.
    """
    result = deepcopy(_RELEASED_V8_DEFAULTS)
    if strategy_kind is not None:
        if strategy_kind not in result["bot"]["long"]["strategy"]:
            raise ValueError(f"unsupported released-v8 strategy kind {strategy_kind!r}")
        result["live"]["strategy_kind"] = strategy_kind
        for side in ("long", "short"):
            for target in (result["bot"][side], result["optimize"]["bounds"][side]):
                target["strategy"] = {strategy_kind: target["strategy"][strategy_kind]}
    return result


def resolve_released_v8_minimum_cost_policy(config):
    """Resolve released missing/default versus explicit-null inheritance.

    This is a local configuration calculation. It performs no market lookups
    and does not replace an authored null with a fixed value in the source.
    """
    defaults = _RELEASED_V8_DEFAULTS
    live = config.get("live", {}).get(
        "filter_by_min_effective_cost", defaults["live"]["filter_by_min_effective_cost"]
    )
    backtest = config.get("backtest", {}).get(
        "filter_by_min_effective_cost", defaults["backtest"]["filter_by_min_effective_cost"]
    )
    if not isinstance(live, bool):
        raise TypeError("live.filter_by_min_effective_cost must be a boolean")
    if backtest is not None and not isinstance(backtest, bool):
        raise TypeError("backtest.filter_by_min_effective_cost must be a boolean or null")
    return {"live": live, "backtest": live if backtest is None else backtest}


def materialize_released_v8_minimum_cost_defaults(config, *, changes):
    """Pin omitted v8 fields while retaining explicit null as inheritance.

    The caller owns its working copy and change list. Sparse coin/scenario
    patches must not pass through this root-default operation.
    """
    resolve_released_v8_minimum_cost_policy(config)
    for section in ("live", "backtest"):
        target = config.setdefault(section, {})
        key = "filter_by_min_effective_cost"
        if key not in target:
            value = _RELEASED_V8_DEFAULTS[section][key]
            target[key] = value
            changes.append(dict(
                path=f"{section}.{key}", old=None, new=value,
                reason="materialized released-v8 default; missing differs from explicit null inheritance",
            ))


def resolve_released_v8_defaults(source):
    """Hydrate canonical released-v8 authoring fields from frozen defaults.

    This reusable migration stage is deliberately separate from v8 alias
    conversion, validation, runtime compilation and I/O. Callers must resolve
    released aliases/conflicts first. Unknown authored fields survive for the
    caller's strict validation; list contents and sparse override maps retain
    authored authority. The returned bounds are the released template ranges;
    optional adaptive dimensions still need their released freezing rules.
    """
    if not isinstance(source, dict):
        raise TypeError("configuration must be a mapping")
    version = source.get("config_version")
    if not isinstance(version, str) or re.fullmatch(r"v?8\.\d+\.\d+", version, re.IGNORECASE) is None:
        raise ValueError("released-v8 defaults require a versioned v8 configuration")
    result = deepcopy(source)
    for section in ("bot", "live", "backtest", "optimize"):
        if not isinstance(result.setdefault(section, {}), dict):
            raise TypeError(f"{section} must be a mapping")
    default_kind = _RELEASED_V8_DEFAULTS["live"]["strategy_kind"]
    kind = str(result["live"].get("strategy_kind") or default_kind).strip().lower() or default_kind
    defaults = get_released_v8_defaults(strategy_kind=kind)
    # The released loader deliberately disabled a fully omitted side and did
    # not inherit the schema's example coin universe into a sparse document.
    for side in ("long", "short"):
        if side not in result["bot"]:
            result["bot"][side] = deepcopy(defaults["bot"][side])
            result["bot"][side]["risk"]["total_wallet_exposure_limit"] = 0.0
    for key in ("approved_coins", "ignored_coins"):
        target = result["live"].setdefault(key, {"long": [], "short": []})
        if isinstance(target, dict) and set(target).issubset({"long", "short"}):
            for side in ("long", "short"):
                target.setdefault(side, [])

    preserve = {("backtest", "reducer"), ("live", "startup_phase_budgets"),
                ("optimize", "fixed_runtime_overrides")}

    def fill(target, template, path=()):
        if path in preserve:
            return
        for key, value in template.items():
            if key not in target:
                target[key] = deepcopy(value)
            elif isinstance(value, dict) and isinstance(target[key], dict):
                fill(target[key], value, (*path, key))

    fill(result, defaults)
    resolve_released_v8_minimum_cost_policy(result)
    return result


def materialize_released_v8_optimizer_bounds(config, *, changes):
    """Preserve released implicit search ranges after explicit structural conversion.

    This stage consumes the converter's canonical paths. Authored and migrated
    coupled-EMA bounds win over frozen released template ranges. Optional
    adaptive dimensions are deliberately absent here: canonical hydration fixes
    them at their configured values, as the released loader did.
    """
    from config.optimize_bounds import flatten_optimize_bounds

    kind = config.get("bot", {}).get("global", {}).get(
        "strategy_kind", _RELEASED_V8_DEFAULTS["live"]["strategy_kind"]
    )
    # Use only the released default resolver, never the evolving v9 template or
    # loaded native metadata, for the ranges that v8 supplied implicitly.
    released = resolve_released_v8_defaults({
        "config_version": RELEASED_V8_SCHEMA_VERSION, "bot": {},
        "live": {"strategy_kind": kind},
    })
    defaults = released["optimize"]["bounds"]
    portfolio = config.get("bot", {}).get("global", {}).get("hsl", {}).get("scope") == "portfolio"
    for side in ("long", "short"):
        shared = defaults[side]
        shared["strategy"] = {kind: shared["strategy"][kind]}
        shared["risk"]["max_positions"] = shared["risk"].pop("n_positions")
        for owner in ("position_exposure_enforcer", "total_exposure_enforcer"):
            shared["risk"][owner] = {"threshold": shared["risk"].pop(f"{owner}_threshold")}
        shared["unstuck"]["exposure_trigger_ratio"] = shared["unstuck"].pop("threshold")
        shared["unstuck"]["ema_distance_fraction"] = shared["unstuck"].pop("ema_dist")
        shared["forager"].pop("volume_drop_pct", None)
        shared["forager"]["score_weights"] = {
            name: shared["forager"].pop(f"score_weights_{name}")
            for name in ("volume", "volatility", "ema_readiness")
        }
        if portfolio:
            shared.pop("hsl", None)
        else:
            shared["hsl"]["drawdown_ratio_threshold"] = shared["hsl"].pop("red_threshold")
            shared["hsl"]["drawdown_ratio_ema_span_minutes"] = shared["hsl"].pop("ema_span_minutes")
    from config.public_names import rewrite_released_public_names

    rewrite_released_public_names({"optimize": {"bounds": defaults}})
    original = config.setdefault("optimize", {}).get("bounds", {})
    rebuilt = deepcopy(original)

    def overlay_missing(target, template):
        if not isinstance(target, dict):
            return
        for key, value in template.items():
            if key not in target:
                target[key] = deepcopy(value)
            elif isinstance(value, dict):
                overlay_missing(target[key], value)

    # Preserve every authored field and malformed container for the strict
    # schema gate. Rebuilding from a flattened projection would erase unknown
    # nested/global fields and could silently turn invalid input into success.
    overlay_missing(rebuilt, defaults)
    config["optimize"]["bounds"] = rebuilt
    if rebuilt != original:
        authored = flatten_optimize_bounds(original, strategy_kind=kind)
        added = sorted(set(flatten_optimize_bounds(defaults, strategy_kind=kind)) - set(authored))
        changes.append(dict(
            path="optimize.bounds", old=deepcopy(original), new=deepcopy(rebuilt),
            reason="materialized released-v8 inherited search ranges before explicit-only v9 bounds",
            materialized_bound_keys=added,
        ))
