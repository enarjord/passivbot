"""Generate the code-owned configuration field/type reference."""

import argparse
import json
from pathlib import Path

from config.field_registry import get_field_registry
from config.field_spec import NO_DEFAULT


DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "ai" / "generated" / "config_fields.md"


def _default_label(field):
    value = field.default
    if value is NO_DEFAULT:
        return "Not declared"
    if isinstance(value, (dict, list)) and value:
        return f"{len(value)} {'members' if isinstance(value, dict) else 'items'} (see template)"
    if field.numeric_type is float and type(value) is int and float(value) == value:
        value = float(value)
    elif field.numeric_type is int and type(value) is float and value.is_integer():
        value = int(value)
    return "`" + json.dumps(value, ensure_ascii=False).replace("|", "\\|") + "`"


def render_reference():
    registry = get_field_registry()
    parts = [
        "# Generated Configuration Field Reference\n\n",
        "<!-- Generated by src/tools/generate_config_field_reference.py; do not edit manually. -->\n\n",
        "Field declarations live in `src/config/field_registry.py`; descriptor types live in "
        "`src/config/field_spec.py`. Defaults remain owned by `src/config/schema.py` and Rust "
        "strategy metadata. Run `PYTHONPATH=src python src/tools/generate_config_field_reference.py "
        "--check` to check this file.\n\n",
        "Types declare canonical serialization. Numeric export changes spelling only when it "
        "preserves the value; it never rounds fractional values into integer fields. Nullability "
        "is separate from numeric type. Existing field validators continue to own accepted inputs "
        "and semantic constraints. A descriptor grants no override or optimization permission.\n\n",
        "`*` denotes one record index or dynamic map key. Coin patches and literal override paths "
        "reuse the addressed field's type. Numeric optimizer bounds reuse their target bot field's "
        "type through the existing optimizer path adapter. Optional fields with no declared default "
        "are documented without supplying runtime authority. This reference lists both supported "
        "strategy kinds; runtime loading retains only the active kind.\n\n",
        "Scope, consumers, domains, override permissions, display order, units/denominators, and "
        "recommended bounds are available as descriptor metadata. Unspecified metadata is unknown, "
        "not a permission or domain assertion; later consumers must not interpret it as authority. "
        "Rust strategy recommendations and fixed-parameter choices come from Rust metadata.\n\n",
    ]
    groups = {}
    for field in registry:
        groups.setdefault(field.path[0], []).append(field)
    for name, fields in sorted(groups.items()):
        parts.extend([
            f"## {name}\n\n",
            "| Field | Type | Default | Source |\n",
            "| --- | --- | --- | --- |\n",
        ])
        for field in sorted(fields, key=lambda field: field.path):
            types = field.type_label.replace("|", "\\|")
            parts.append(f"| `{'.'.join(field.path)}` | {types} | {_default_label(field)} | {field.source} |\n")
        parts.append("\n")
    return "".join(parts)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args(argv)
    rendered = render_reference()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            print(f"stale generated documentation: {args.output}")
            return 1
        print(f"generated documentation is current: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
