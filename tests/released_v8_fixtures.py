def released_v8_example_metrics(name):
    """Exercise every released example's exact metric selections, offline."""
    from copy import deepcopy

    selection = deepcopy(_RELEASED_V8_EXAMPLE_METRICS[name])
    source = get_released_v8_defaults(strategy_kind=selection.pop("strategy_kind"))
    source["optimize"]["scoring"] = selection.pop("scoring")
    source["optimize"]["limits"] = selection.pop("limits")
    source["backtest"].update(selection)
    return source


